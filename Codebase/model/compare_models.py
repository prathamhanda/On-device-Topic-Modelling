"""Compare all implemented SMS keyword extraction model profiles.

The script reads/evaluates metrics for MobileBERT, DistilBERT, and BERT-base and
writes a compact CSV plus a human-readable Markdown comparison.

Examples:
    python -m model.compare_models
    python -m model.compare_models --evaluate-missing
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent.parent))
from model.config import DEFAULT_PROFILE, MODEL_PROFILES, OUTPUT_DIR, metrics_path
import json


def resolve_profiles(profile_args: list[str]) -> list[str]:
    if not profile_args or "all" in profile_args:
        return list(MODEL_PROFILES.keys())
    unknown = [p for p in profile_args if p not in MODEL_PROFILES]
    if unknown:
        valid = ", ".join(["all", *sorted(MODEL_PROFILES)])
        raise ValueError(f"Unknown profiles {unknown}. Valid values: {valid}")
    return profile_args


def load_or_evaluate(
    profile_name: str,
    split: str,
    evaluate_missing: bool,
    force_cpu: bool,
) -> dict[str, Any] | None:
    path = metrics_path(profile_name, split=split)
    if path.exists():
        return json.loads(path.read_text())
    if evaluate_missing:
        try:
            from model.evaluate import evaluate_checkpoint

            return evaluate_checkpoint(
                profile_name=profile_name,
                split=split,
                force_cpu=force_cpu,
                metrics_out=path,
                save_metrics=True,
            )
        except (FileNotFoundError, ImportError, ModuleNotFoundError, ValueError) as exc:
            print(f"[WARN] Could not evaluate {profile_name}: {exc}")
    return None


def row_from_report(profile_name: str, report: dict[str, Any] | None, split: str) -> dict[str, Any]:
    profile = MODEL_PROFILES[profile_name]
    if report is None:
        return {
            "profile": profile_name,
            "model_name": profile.model_name,
            "split": split,
            "status": "missing metrics/checkpoint",
            "accuracy": "",
            "keyword_f1": "",
            "keyword_precision": "",
            "keyword_recall": "",
            "macro_f1": "",
            "weighted_f1": "",
            "params_m": "",
            "checkpoint_mb": "",
            "decision_threshold": "",
            "metrics_file": str(metrics_path(profile_name, split=split)),
        }

    metrics = report.get("metrics", {})
    model = report.get("model", {})
    total_params = model.get("total_parameters")
    params_m = round(total_params / 1_000_000, 2) if isinstance(total_params, int) else ""
    return {
        "profile": profile_name,
        "model_name": report.get("model_name", profile.model_name),
        "split": report.get("split", split),
        "status": "ok",
        "accuracy": _fmt(metrics.get("accuracy")),
        "keyword_f1": _fmt(metrics.get("f1")),
        "keyword_precision": _fmt(metrics.get("precision")),
        "keyword_recall": _fmt(metrics.get("recall")),
        "macro_f1": _fmt(metrics.get("macro_f1")),
        "weighted_f1": _fmt(metrics.get("weighted_f1")),
        "params_m": params_m,
        "checkpoint_mb": report.get("checkpoint_size_mb", ""),
        "decision_threshold": report.get("decision_threshold", "argmax"),
        "metrics_file": str(metrics_path(profile_name, split=split)),
    }


def _fmt(value: Any) -> str:
    return "" if value is None else f"{float(value):.4f}"


def write_csv(rows: list[dict[str, Any]], out_csv: Path) -> None:
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(rows[0].keys()) if rows else []
    with out_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(rows: list[dict[str, Any]], out_md: Path, split: str) -> None:
    out_md.parent.mkdir(parents=True, exist_ok=True)
    headers = [
        "profile",
        "model_name",
        "status",
        "accuracy",
        "keyword_f1",
        "keyword_precision",
        "keyword_recall",
        "macro_f1",
        "params_m",
        "checkpoint_mb",
        "decision_threshold",
    ]
    lines = [
        f"# Model Comparison ({split} split)",
        "",
        "This file is generated by `python -m model.compare_models`.",
        "",
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(h, "")) for h in headers) + " |")
    lines.extend(
        [
            "",
            "## Reading the table",
            "",
            "- `accuracy` is token-level accuracy after ignored sub-tokens/padding are removed.",
            "- `keyword_f1`, `keyword_precision`, and `keyword_recall` focus on label 1, the extracted keyword class.",
            "- `params_m` is the model parameter count in millions; `checkpoint_mb` is the saved checkpoint size.",
            "- Missing rows mean the profile has been implemented but has not been trained/evaluated yet.",
        ]
    )
    out_md.write_text("\n".join(lines) + "\n")


def compare_models(
    profiles: list[str],
    split: str = "val",
    evaluate_missing: bool = False,
    force_cpu: bool = False,
    out_csv: Path | None = None,
    out_md: Path | None = None,
) -> list[dict[str, Any]]:
    resolved_profiles = resolve_profiles(profiles)
    rows = []
    for profile_name in resolved_profiles:
        report = load_or_evaluate(profile_name, split, evaluate_missing, force_cpu)
        rows.append(row_from_report(profile_name, report, split))

    csv_path = out_csv or (OUTPUT_DIR / f"model_comparison_{split}.csv")
    md_path = out_md or (OUTPUT_DIR / f"model_comparison_{split}.md")
    write_csv(rows, csv_path)
    write_markdown(rows, md_path, split)
    print(f"[INFO] Comparison CSV saved to {csv_path}")
    print(f"[INFO] Comparison report saved to {md_path}")
    return rows


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compare implemented SMS keyword models")
    parser.add_argument(
        "--profiles",
        nargs="+",
        default=["all"],
        help="Profiles to compare, or 'all'",
    )
    parser.add_argument("--split", choices=["train", "val", "all"], default="val")
    parser.add_argument(
        "--evaluate-missing",
        action="store_true",
        help="Run model.evaluate for missing metrics when checkpoints exist",
    )
    parser.add_argument("--force-cpu", action="store_true")
    parser.add_argument("--out-csv", type=Path, default=None)
    parser.add_argument("--out-md", type=Path, default=None)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    compare_models(
        profiles=args.profiles,
        split=args.split,
        evaluate_missing=args.evaluate_missing,
        force_cpu=args.force_cpu,
        out_csv=args.out_csv,
        out_md=args.out_md,
    )


if __name__ == "__main__":
    main()
